"""Run the same five evaluation queries against keyword and semantic search."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from search import SemanticSearchEngine, keyword_search

PROJECT_ROOT = Path(__file__).resolve().parent
COMPARISON_PATH = PROJECT_ROOT / "comparison.md"
BEGIN_MARKER = "<!-- BEGIN GENERATED RESULTS -->"
END_MARKER = "<!-- END GENERATED RESULTS -->"

TEST_QUERIES = [
    "My notebook goes dead before the lecture ends.",
    "My handset cannot browse while I am indoors.",
    "I made a mistake and now the earlier material is gone.",
    "The machine is scorching and no longer responds.",
    "Booting is painfully sluggish, and the desktop takes forever to appear.",
]


def make_results_section(engine: SemanticSearchEngine) -> str:
    sections: list[str] = [
        "## Generated results",
        "",
        "> Generated by `python compare_search.py` using the current local model and dataset. "
        "Cosine similarity and keyword-overlap scores are ranking signals, not probabilities.",
        "",
    ]

    for number, query in enumerate(TEST_QUERIES, start=1):
        semantic = engine.search(query, top_k=3)
        keyword = keyword_search(query, engine.records, top_k=3)
        sections.extend([f"### Query {number}: {query}", "", "**Semantic search — top 3**", ""])
        if semantic:
            sections.extend([
                "| Rank | ID | FAQ question | Cosine similarity |",
                "|---:|---|---|---:|",
            ])
            for rank, item in enumerate(semantic, start=1):
                question = item["question"].replace("|", "\\|")
                sections.append(f"| {rank} | {item['id']} | {question} | {item['score']:.4f} |")
        else:
            sections.append("No semantic results returned.")

        sections.extend(["", "**Keyword search — matches with word overlap**", ""])
        if keyword:
            sections.extend([
                "| Rank | ID | FAQ question | Query-token overlap | Shared terms |",
                "|---:|---|---|---:|---|",
            ])
            for rank, item in enumerate(keyword, start=1):
                question = item["question"].replace("|", "\\|")
                terms = ", ".join(item["matched_terms"])
                sections.append(
                    f"| {rank} | {item['id']} | {question} | {item['score']:.1%} | {terms} |"
                )
        else:
            sections.append("No keyword match: the query has no non-stopword terms in common with the FAQ text.")
        sections.extend(["", "**Manual relevance note:** _After reviewing the actual results, state whether the semantic top result is relevant and whether keyword search missed it._", ""])

    return "\n".join(sections).rstrip()


def update_comparison_file(generated_section: str) -> None:
    if not COMPARISON_PATH.exists():
        raise FileNotFoundError(f"Could not find {COMPARISON_PATH.name}.")
    text = COMPARISON_PATH.read_text(encoding="utf-8")
    if BEGIN_MARKER not in text or END_MARKER not in text:
        raise ValueError("comparison.md is missing the generated-results markers; restore the starter file.")
    before, remainder = text.split(BEGIN_MARKER, maxsplit=1)
    _, after = remainder.split(END_MARKER, maxsplit=1)
    updated = f"{before}{BEGIN_MARKER}\n{generated_section}\n{END_MARKER}{after}"
    COMPARISON_PATH.write_text(updated, encoding="utf-8")


def print_console_summary(engine: SemanticSearchEngine) -> None:
    print("\nFIVE-QUERY COMPARISON")
    print("=" * 72)
    for number, query in enumerate(TEST_QUERIES, start=1):
        semantic = engine.search(query, top_k=3)
        keyword = keyword_search(query, engine.records, top_k=3)
        print(f"\n{number}. QUERY: {query}")
        if semantic:
            first = semantic[0]
            print(f"   Semantic top 1: [{first['id']}] {first['question']} (cosine={first['score']:.4f})")
        if keyword:
            first_kw = keyword[0]
            print(
                f"   Keyword top 1:  [{first_kw['id']}] {first_kw['question']} "
                f"(overlap={first_kw['score']:.1%}; shared={', '.join(first_kw['matched_terms'])})"
            )
        else:
            print("   Keyword top 1:  NO MATCH (no shared non-stopword terms)")


def main() -> None:
    try:
        engine = SemanticSearchEngine()
        print_console_summary(engine)
        generated = make_results_section(engine)
        update_comparison_file(generated)
    except (FileNotFoundError, RuntimeError, ValueError) as exc:
        raise SystemExit(f"\nCOMPARISON ERROR: {exc}") from exc

    print(f"\nUpdated {COMPARISON_PATH.name} with actual results.")
    print("Review the generated results and complete the manual relevance notes before submission.")


if __name__ == "__main__":
    main()
